// Helper to match a user-entered city name to our curated catalog (supporting Chinese or English names)
export function findCuratedCity(query: string): City | undefined {
  const normalized = query.trim().toLowerCase().replace(/[市省州]$/, "");
  if (!normalized) return undefined;

  return CITIES_DATA.find((c) => {
    const zh = c.name.toLowerCase();
    const en = c.englishName.toLowerCase();
    return (
      zh === normalized ||
      en === normalized ||
      zh.includes(normalized) ||
      en.includes(normalized)
    );
  });
}
